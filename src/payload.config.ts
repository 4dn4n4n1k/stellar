function getDatabaseSSL() {
  const dbUri = process.env.DATABASE_URI;
  if (!dbUri || dbUri.includes('localhost') || dbUri.includes('127.0.0.1')) {
    return false;
  }

  // 1. Optional environment variable override (e.g. custom CA cert in deployment)
  const envCa = process.env.DATABASE_SSL_CA
    ? process.env.DATABASE_SSL_CA.replace(/\\n/g, '\n')
    : undefined;

  // 2. Local cert file if present in development
  let localCa: string | undefined;
  try {
    const certPath = path.resolve(dirname, '../certs/prod-ca-2021.crt');
    if (fs.existsSync(certPath)) {
      localCa = fs.readFileSync(certPath, 'utf8');
    }
  } catch {
    // Ignore and fall through to embedded Supabase root CA
  }

  return {
    rejectUnauthorized: true,
    ca: envCa || localCa || SUPABASE_ROOT_CA,
  };
}

